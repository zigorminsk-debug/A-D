    fun search(query: String): List<DrugRef> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return all()
        return all().filter {
            it.name.lowercase().contains(q) ||
                it.group.lowercase().contains(q) ||
                it.generics.lowercase().contains(q)
        }
    }
