def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), fill)
    tcPr.append(shd)

def cell_text(cell, text, bold=False, size=9.5, color=None):
    cell.text = ""
    p = cell.paragraphs[0]; p.paragraph_format.space_after = Pt(2)
    r = p.add_run(text); r.font.size = Pt(size); r.font.bold = bold
    if color: r.font.color.rgb = color

def make_table(headers, rows, widths=None, body_size=9):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htxt in enumerate(headers):
        c = t.rows[0].cells[i]
        cell_text(c, htxt, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF)); shade(c, HDR_FILL)
    for row in rows:
        cs = t.add_row().cells
        for i, v in enumerate(row): cell_text(cs[i], v, size=body_size)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows: row.cells[i].width = Cm(w)
    return t

def bullets(items, size=10.5):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(it); r.font.size = Pt(size)

def para(text, bold=False, size=10.5, italic=False, align=None, justify=False):
    p = doc.add_paragraph()
    if align: p.alignment = align
    elif justify: p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    r = p.add_run(text); r.font.size = Pt(size); r.bold = bold; r.italic = italic
    return p

